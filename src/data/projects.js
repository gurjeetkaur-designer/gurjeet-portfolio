// All images in src/assets/work are collected here. Reference one with
// work('folder/file.webp'). A typo throws a clear error at startup instead of
// silently rendering a broken image.
const images = import.meta.glob('../assets/work/**/*.{webp,jpg,jpeg,png,avif}', {
  eager: true,
  import: 'default',
});

function work(path) {
  const src = images[`../assets/work/${path}`];
  if (!src) throw new Error(`Image not found: src/assets/work/${path}`);
  return src;
}

