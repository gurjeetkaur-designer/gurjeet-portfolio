// All media in src/assets/work is collected here. Reference an image with
// work('folder/file.webp'). A typo throws a clear error at startup instead of
// silently rendering a broken image.
const media = import.meta.glob('../assets/work/**/*.{webp,jpg,jpeg,png,avif,mp4}', {
  eager: true,
  import: 'default',
});

function work(path) {
  const src = media[`../assets/work/${path}`];
  if (!src) throw new Error(`File not found: src/assets/work/${path}`);
  return src;
}

// A video and the poster frame saved next to it share a name: clip('motion/holi')
// uses motion/holi.mp4 and motion/holi.webp.
function clip(path) {
  return { image: work(`${path}.webp`), video: work(`${path}.mp4`) };
}

// A multi-slide post. The card shows the first slide; the viewer shows them all.
function carousel(paths) {
  const gallery = paths.map((p) => work(`${p}.webp`));
  return { image: gallery[0], gallery };
}

